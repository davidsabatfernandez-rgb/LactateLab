/* ── Context ── */
type LangCtx = { lang: Lang; t: (key: string) => string; setLang: (l: Lang) => void };
const Ctx = createContext<LangCtx>({ lang: "en", t: (k) => k, setLang: () => {} });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangRaw] = useState<Lang>(() => {
    const stored = localStorage.getItem("pa-lang") as Lang | null;
    if (stored && T[stored]) return stored;
    const nav = navigator.language.slice(0, 2).toLowerCase();
    if (nav === "es") return "es";
    if (nav === "de") return "de";
    if (nav === "nb" || nav === "nn" || nav === "no") return "no";
    if (nav === "fr") return "fr";
    return "en";
  });

  const setLang = useCallback((l: Lang) => {
    setLangRaw(l);
    localStorage.setItem("pa-lang", l);
  }, []);

  const t = useCallback((key: string): string => {
    return T[lang]?.[key] ?? T.en[key] ?? key;
  }, [lang]);

  return <Ctx.Provider value={{ lang, t, setLang }}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx);
}
